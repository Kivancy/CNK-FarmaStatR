#   1) Tsong ve ark. 1996, Tablo 1 (düzeltilmiş: REF tablet 4, 30 dk = 78.45) ve
#      Tablo 3 (standart lotlar STD1, STD2) — Bölüm 1A/1B validasyon verisi
#   2) Noce ve ark. 2020, Tablo 1 (Ürün 1, 2, 3) — Bölüm 2 validasyon verisi
# =============================================================================

uzun_format <- function(M, urun, zamanlar) {
  data.frame(Product = urun,
             Unit    = rep(seq_len(nrow(M)), times = ncol(M)),
             Time    = rep(zamanlar, each = nrow(M)),
             Diss    = as.vector(M),
             stringsAsFactors = FALSE)
}

